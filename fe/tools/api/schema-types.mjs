/** Render the structural JSON Schema vocabulary emitted by the Host. Fail on unknown shapes.
 * @param {Record<string, any> | boolean} schema
 * @returns {string}
 */
export function schemaType(schema) {
  if (schema === true) return 'unknown';
  if (schema === false) return 'never';
  if (schema.$ref) {
    if (!schema.$ref.startsWith('#/components/schemas/')) throw new Error(`Unsupported reference: ${schema.$ref}`);
    return schema.$ref.slice('#/components/schemas/'.length);
  }
  if (schema.anyOf) return schema.anyOf.map(schemaType).join(' | ');
  if (schema.enum) return schema.enum.map((/** @type {unknown} */ value) => JSON.stringify(value)).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map((/** @type {string} */ type) => schemaType({ ...schema, type })).join(' | ');
  if (schema.type === 'null') return 'null';
  if (schema.type === 'string') return 'string';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'array') return `Array<${schemaType(schema.items)}>`;
  if (schema.type === 'object') {
    const properties = Object.entries(schema.properties ?? {}).map(([name, value]) =>
      `${JSON.stringify(name)}${schema.required?.includes(name) ? '' : '?'}: ${schemaType(value)}`);
    if (schema.additionalProperties) properties.push(`[key: string]: ${schemaType(schema.additionalProperties)}`);
    if (properties.length === 0) return `Record<string, ${schema.additionalProperties === false ? 'never' : 'unknown'}>`;
    return `{ ${properties.join('; ')} }`;
  }
  if (Object.keys(schema).length === 0) return 'unknown'; // Opaque JsonElement.
  throw new Error(`Unsupported Host schema: ${JSON.stringify(schema)}`);
}

/** @param {Record<string, Record<string, any> | boolean>} schemas @returns {string} */
export function generateWire(schemas) {
  const entries = Object.entries(schemas).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  for (const [name] of entries) {
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) throw new Error(`Unsupported contract name: ${name}`);
  }
  return '// Generated by npm run gen:api from the real Host endpoint table. Do not edit.\n\n'
    + entries.map(([name, schema]) => `export type ${name} = ${schemaType(schema)};`).join('\n') + '\n';
}

/** @param {Record<string, Record<string, any> | boolean>} schemas @param {string} source */
export function assertWireCurrent(schemas, source) {
  if (source !== generateWire(schemas)) throw new Error('wire.ts drifted from Host OpenAPI. Run npm run gen:api.');
}
